export function getRoom(id: string): Room | undefined {
  return rooms.find((room) => room.id === id);
}

export function roomsIn(placeId: string): Room[] {
  return rooms.filter((room) => room.placeId === placeId);
}

export const bookableRooms = rooms.filter((room) => room.bookable);
