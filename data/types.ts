export type PlaceId =
  | "library"
  | "aula"
  | "pulse"
  | "echo"
  | "eemcs"
  | "bk-city"
  | "x"
  | "science-centre"
  | "botanical-garden"
  | "mekelpark"
  | "delft-centraal"
  | "tram-19"
  | "bike-parking"
  | "food"
  | "services-desk";

export type CategoryId =
  "getting-here" | "study" | "eat" | "campus-life" | "services";

export type RoomType = "silent" | "group" | "computer";

/** Minutes since midnight, campus time. */
export type Minutes = number;

/** One opening span. `close` may be 1440 for midnight. */
export interface Span {
  open: Minutes;
  close: Minutes;
}

/** Index 0 is Monday. `null` means closed that day. */
export type WeekHours = [
  Span | null,
  Span | null,
  Span | null,
  Span | null,
  Span | null,
  Span | null,
  Span | null,
];

export interface Place {
  id: PlaceId;
  name: string;
  shortName: string;
  categories: CategoryId[];
  /** Extra words search should match, like "EWI" or "faculty". */
  searchTerms: string[];
  isFaculty: boolean;
  summary: string;
  address: string | null;
  /** `null` means always open, like a park. */
  hours: WeekHours | null;
  gettingThere: string;
}

export interface Facilities {
  coffee: boolean;
  daylight: boolean;
  toilet: boolean;
  sockets: number;
  whiteboard: boolean;
  monitor: boolean;
}

export interface BookingRules {
  daysAhead: number;
  slotMinutes: number;
  longestMinutes: number;
}

export interface Room {
  id: string;
  placeId: PlaceId;
  name: string;
  floor: string;
  type: RoomType;
  seats: number;
  facilities: Facilities;
  hasSensor: boolean;
  bookable: boolean;
  rules: BookingRules | null;
  directions: string[];
}

export interface CampusEvent {
  id: string;
  title: string;
  placeId: PlaceId;
  /** Days from today, so the mock never goes stale. */
  dayOffset: number;
  start: Minutes;
  end: Minutes;
  summary: string;
  link: string;
  tone: "cyan" | "green" | "orange" | "violet";
}

export interface Notice {
  id: string;
  kind: "warning" | "notice";
  /** `null` means the whole campus. */
  placeId: PlaceId | null;
  title: string;
  body: string;
}

export interface FaqGroup {
  title: string;
  items: { question: string; answer: string }[];
}

/* ---------- Campus geometry, generated by scripts/build-campus.mjs ---------- */

/** Scene metres from the origin: x east, z south. Three.js y is up. */
export type ScenePoint = [x: number, z: number];

export interface PlaceGeo {
  lat: number;
  lon: number;
  /** Where the label sits and the camera looks. */
  anchor: ScenePoint;
  /** Roof height at the anchor in metres, 0 for flat places. */
  height: number;
  /** GLB node names that belong to this place. Empty for areas and points. */
  meshes: string[];
  /** Spots for places that are many points: tram stops, bike parking, cafés. */
  markers: { name: string; point: ScenePoint }[];
  /** Outline for areas like parks and gardens. */
  area: ScenePoint[] | null;
  /** For places outside the scene: direction from the origin and distance. */
  offscene: { bearing: number; distance: number } | null;
}

export interface CampusGeo {
  origin: { lat: number; lon: number };
  bounds: { min: ScenePoint; max: ScenePoint };
  places: Record<PlaceId, PlaceGeo>;
  /** Walking route from the nearest tram 19 stop to the place. Empty when there is none. */
  routes: Partial<Record<PlaceId, ScenePoint[]>>;
  tramLine: ScenePoint[][];
  trees: ScenePoint[];
  bikeParking: ScenePoint[];
  attribution: string[];
}
